#!/usr/bin/env node
// Regenerates the card portraits: node generate.js [id ...] [--out dir] [--png dir]
//   ids     only render these cards (default: all in cards.json)
//   --out   output folder for the JPEGs (default: the game's Card/Portraits folder)
//   --png   also keep lossless PNGs here (for previews)
//   --cards use another card file (for experiments; CREDITS.md is only written for the default cards.json)
//   --credits-only  just rewrite CREDITS.md
'use strict';
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const { chromium } = require('playwright');
const { resolve } = require('./style');

const ROOT = __dirname;
const DEFAULT_OUT = path.join(ROOT, '..', '..', 'src', 'Souls.Web', 'wwwroot', 'Content', 'Images', 'Card', 'Portraits');
// The game's original art lives in the same folder and must never be overwritten.
const PROTECTED = new Set(['0.png', '1.png', '2.png', '3.png', '4.png', '5.png', '6.png', '15.png', '15.gif', '6.gif', '16.jpg', '18.png']);
const MAX_BYTES = 200 * 1024;

function parseArgs(argv) {
  const a = { ids: [], out: DEFAULT_OUT, png: null, cards: path.join(ROOT, 'cards.json') };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') a.out = argv[++i];
    else if (argv[i] === '--png') a.png = argv[++i];
    else if (argv[i] === '--cards') a.cards = path.resolve(argv[++i]);
    else if (argv[i] === '--credits-only') a.creditsOnly = true;
    else a.ids.push(argv[i]);
  }
  return a;
}

function fileName(card) { return `${card.id}.jpg`; }
// every game-icons icon a card draws: its layers plus the optional background sigil
function iconsOf(card) { return card.layers.map(l => l.icon).concat(card.sigil ? [card.sigil.icon] : []); }

function writeCredits(cards, outDir) {
  const authors = JSON.parse(fs.readFileSync(path.join(ROOT, 'icon-authors.json'), 'utf8'));
  const info = require('@iconify-json/game-icons/info.json');
  const used = new Map();
  for (const c of cards) for (const icon of iconsOf(c)) {
    if (!used.has(icon)) used.set(icon, []);
    const label = `${c.id} ${c.name}`;
    if (!used.get(icon).includes(label)) used.get(icon).push(label);
  }
  const rows = [...used.keys()].sort().map(icon => {
    const a = authors[icon];
    if (!a) throw new Error(`no author recorded for icon ${icon}; run: node fetch-authors.js`);
    return `| \`${icon}\` | ${a.name} | [svg](https://game-icons.net/1x1/${a.slug}/${icon}.html) | ${used.get(icon).join(', ')} |`;
  });
  const md = `# Card portrait credits

The card portraits in this folder **other than** the game's original art (0.png, 1.png, 2.png, 3.png, 4.png, 5.png,
6.png, 6.gif, 15.png, 15.gif, 16.jpg, 18.png) were generated by \`tools/card-art\` (see its README). Each is an
original rendering built around silhouettes from **game-icons.net** (https://game-icons.net), licensed under
**Creative Commons Attribution 3.0** (CC BY 3.0, https://creativecommons.org/licenses/by/3.0/). The icons were
taken from the npm package \`@iconify-json/game-icons\` ${require('@iconify-json/game-icons/package.json').version}
(set author: ${info.author.name}, ${info.author.url}; license: ${info.license.title}); the per-icon authors below
are the contributor folders of the game-icons.net repository. The icons were recoloured, lit, combined and
composited into painted scenes; these are derivative works and are shared under the same attribution terms.

Icons made by the game-icons.net contributors listed below, from https://game-icons.net, CC BY 3.0.

| Icon | Author | Source | Used for |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
  fs.writeFileSync(path.join(outDir, 'CREDITS.md'), md);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const data = JSON.parse(fs.readFileSync(args.cards, 'utf8'));
  const icons = require('@iconify-json/game-icons/icons.json').icons;
  if (args.creditsOnly) { writeCredits(data.cards, args.out); return; }
  let cards = data.cards;
  if (args.ids.length) cards = cards.filter(c => args.ids.includes(String(c.id)));
  if (!cards.length) throw new Error('no cards selected');
  fs.mkdirSync(args.out, { recursive: true });
  if (args.png) fs.mkdirSync(args.png, { recursive: true });

  const browser = await chromium.launch();
  const page = await browser.newPage();
  page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') console.log('[page]', m.text()); });
  page.on('pageerror', e => console.log('[page error]', e.message));
  await page.goto('file://' + path.join(ROOT, 'lib', 'render.html'));
  await page.waitForFunction(() => window.rendererReady === true);

  for (const card of cards) {
    const name = fileName(card);
    if (PROTECTED.has(name)) throw new Error(`refusing to overwrite original art ${name}`);
    const spec = resolve(card, icons);
    const res = await page.evaluate(s => window.renderCard(s), spec);
    const png = Buffer.from(res.png.split(',')[1], 'base64');
    if (args.png) fs.writeFileSync(path.join(args.png, `${card.id}.png`), png);
    let q = 86, jpg;
    for (;;) {
      jpg = await sharp(png).removeAlpha().toColorspace('srgb')
        .jpeg({ quality: q, mozjpeg: true, chromaSubsampling: '4:4:4' }).toBuffer();
      if (jpg.length <= MAX_BYTES || q <= 70) break;
      q -= 3;
    }
    fs.writeFileSync(path.join(args.out, name), jpg);
    console.log(`${String(card.id).padEnd(9)} ${card.name.padEnd(18)} ${name.padEnd(14)} q${q} ${(jpg.length / 1024).toFixed(0)} KB  ${res.ms} ms`);
  }
  await browser.close();
  if (args.cards === path.join(ROOT, 'cards.json')) writeCredits(data.cards, args.out);
}

main().catch(e => { console.error(e); process.exit(1); });
